/**
 * Build `lib/` from `src/`:
 * - the Host half is plain ESM compiled by tsc (declarations included);
 * - the browser half is bundled by esbuild into the `__ModuleLoader__` factory
 *   form the Web shell expects.
 */
import { execFileSync } from 'node:child_process'
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { build } from 'esbuild'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const libDir = resolve(root, 'lib')
const require = createRequire(import.meta.url)
const pkg = JSON.parse(await readFile(resolve(root, 'package.json'), 'utf8'))

/** Compile the Host half with the TypeScript compiler that this workspace installs. */
function buildHost() {
  const tsc = require.resolve('typescript/bin/tsc')
  execFileSync(process.execPath, [tsc, '-p', resolve(root, 'tsconfig.build.json')], {
    cwd: root,
    stdio: 'inherit',
  })
}

/** Bundle the browser half and wrap it in the module-loader contract. */
async function buildClient() {
  const result = await build({
    absWorkingDir: root,
    entryPoints: ['src/client/index.tsx'],
    bundle: true,
    format: 'cjs',
    platform: 'browser',
    target: 'es2022',
    jsx: 'automatic',
    // `react` and its JSX runtime are baseline modules the Web shell seeds.
    // The primitives package is seeded too, and its prebuilt copy already owns
    // the markdown/KaTeX/Shiki dependencies, so only the bare import is emitted.
    external: [
      'react',
      'react-dom',
      'react/jsx-runtime',
      '@deepseek-ai/dsh-client-ui-primitives',
    ],
    // React Flow's base stylesheet is inlined into the bundle as text and
    // rendered by the chart's own <style> tag, next to the plugin styles.
    loader: { '.css': 'text' },
    logLevel: 'warning',
    write: false,
    charset: 'utf8',
  })

  const [output] = result.outputFiles
  if (output === undefined) throw new Error('client build produced no output')

  const indented = output.text
    .split('\n')
    .map((line) => (line.length > 0 ? `\t\t${line}` : line))
    .join('\n')

  const bundle = `/* ${pkg.name} ${pkg.version} — generated by scripts/build.mjs, do not edit. */
window.__ModuleLoader__.load({
\tid: ${JSON.stringify(pkg.name)},
\tfactory: (require) => {
\t\tvar module = { exports: {} };
\t\tvar exports = module.exports;
${indented}
\t\treturn module.exports;
\t}
});
`

  await writeFile(resolve(libDir, 'client.js'), bundle, 'utf8')
}

await rm(libDir, { recursive: true, force: true })
await mkdir(libDir, { recursive: true })
buildHost()
await buildClient()
process.stdout.write(`built ${pkg.name}@${pkg.version} → lib/\n`)
